let lang = "en";

export function setLanguage(l) {
  lang = STRINGS[l] ? l : "en";
  document.documentElement.lang = lang;
  document.documentElement.dir = langInfo().dir;
}

export function langInfo(code = lang) {
  return LANGUAGES.find((x) => x.code === code) ?? LANGUAGES[1];
}

/** `<option>`s for a language picker. */
export function languageOptions(selected) {
  return LANGUAGES.map((l) => `<option value="${l.code}" ${l.code === selected ? "selected" : ""}>${l.name}</option>`).join("");
}

export function getLanguage() {
  return lang;
}

export function t(key, vars = {}) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (typeof s === "string") {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

const BN_DIGITS = "০১২৩৪৫৬৭৮৯";
export function num(n) {
  const s = String(n);
  return lang === "bn" ? s.replace(/[0-9]/g, (d) => BN_DIGITS[d]) : s;
}
