-- FocusFort partner/sync backend schema for Supabase (Postgres).
-- Mirrors backend/src/store.mjs. Devices authenticate with their own secret
-- through Edge Functions (service role); there is no direct client access,
-- so RLS is enabled with no policies for anon/authenticated roles.

create extension if not exists pgcrypto;

create table public.devices (
  id                uuid primary key default gen_random_uuid(),
  secret_hash       text not null,                -- sha256(device_secret), hex
  name              text not null default 'PC' check (char_length(name) <= 80),
  os                text not null default '' check (os in ('', 'windows', 'macos', 'linux')),
  version           text not null default '',
  protection_level  text not null default 'off' check (protection_level in ('off', 'mindful', 'committed', 'partner')),
  tamper_alerts     boolean not null default false,
  partner_name      text check (char_length(partner_name) <= 80),
  partner_email     text check (partner_email ~* '^[^\s@]+@[^\s@]+\.[^\s@]+$'),
  language          text not null default 'bn' check (language in ('bn', 'en')),
  last_heartbeat_at timestamptz,
  alert_sent_at     timestamptz,
  uninstalled_at    timestamptz,
  created_at        timestamptz not null default now()
);

create table public.requests (
  device_id       uuid not null references public.devices(id) on delete cascade,
  id              text not null check (char_length(id) <= 64),   -- request id generated by the agent
  kind            text not null check (kind in ('uninstall', 'change_protection', 'end_session')),
  reason          text not null default '' check (char_length(reason) <= 500),
  auto_approve_at timestamptz,
  status          text not null default 'pending' check (status in ('pending', 'approved', 'denied')),
  token_hash      text not null unique,          -- sha256(approval link token), hex
  decided_at      timestamptz,
  created_at      timestamptz not null default now(),
  primary key (device_id, id)
);

create table public.outbox (
  id         uuid primary key default gen_random_uuid(),
  "to"       text not null,
  subject    text not null,
  body       text not null,
  created_at timestamptz not null default now(),
  sent_at    timestamptz
);

create index devices_silent_idx on public.devices (last_heartbeat_at)
  where tamper_alerts and uninstalled_at is null;
create index outbox_unsent_idx on public.outbox (created_at) where sent_at is null;

alter table public.devices  enable row level security;
alter table public.requests enable row level security;
alter table public.outbox   enable row level security;

-- Effective status: pending requests auto-approve after their deadline.
create or replace function public.request_status(r public.requests)
returns text language sql stable as $$
  select case when r.status = 'pending' and r.auto_approve_at is not null and r.auto_approve_at <= now()
              then 'approved' else r.status end
$$;

-- Devices with tamper alerts on that stopped reporting 30+ minutes ago and
-- have not been alerted for this silence yet. Called every minute by pg_cron
-- (or a scheduled Edge Function) which then writes to the outbox.
create or replace function public.silent_devices()
returns setof public.devices language sql stable as $$
  select * from public.devices d
  where d.tamper_alerts
    and d.uninstalled_at is null
    and d.last_heartbeat_at is not null
    and d.last_heartbeat_at < now() - interval '30 minutes'
    and (d.alert_sent_at is null or d.alert_sent_at < d.last_heartbeat_at)
$$;
